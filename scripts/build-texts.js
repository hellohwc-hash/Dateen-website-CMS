// Scans src/*.njk for <!--E:key|Section|Label-->...<!--/E--> markers and writes
// worker/texts-manifest.js (the list of editable texts the admin shows).
// Runs automatically as part of `npm run build`.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PAGES = [
  ["home", "index", "Home", "/"],
  ["catering", "catering", "Catering Service", "/catering.html"],
  ["bento", "bento-menu", "Bento Menu", "/bento-menu.html"],
  ["bungkus", "bungkus", "Bungkus Supply", "/bungkus.html"],
  ["vegetarian", "vegetarian", "Vegetarian Catering", "/vegetarian.html"],
  ["contact", "contact", "Contact", "/contact.html"],
];
const ENT = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", mdash: "—", ndash: "–", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", middot: "·", hellip: "…", times: "×" };
function decode(s) {
  return s.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (m, e) => {
    if (e[0] === "#") return String.fromCodePoint(e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
    return ENT[e.toLowerCase()] != null ? ENT[e.toLowerCase()] : m;
  });
}
// HTML fragment -> the simple text format editors use
function toText(html) {
  return decode(
    html.replace(/\s+/g, " ").trim()
      .replace(/\s*<br\s*\/?>\s*/gi, "\n")
      .replace(/<span class="em"[^>]*>([\s\S]*?)<\/span>/g, "*$1*")
      .replace(/<(b|strong)>([\s\S]*?)<\/\1>/g, "**$2**")
      .replace(/<(i|em)>([\s\S]*?)<\/\1>/g, "_$2_")
      .replace(/<!--[\s\S]*?-->/g, "")
  );
}

const items = [];
const seen = new Set();
for (const [page, file, title, url] of PAGES) {
  const src = fs.readFileSync(path.join(ROOT, "src", file + ".njk"), "utf8");
  const re = /<!--E:([\w.-]+)\|([^|]*)\|([^>]*?)-->([\s\S]*?)<!--\/E-->/g;
  let m;
  while ((m = re.exec(src))) {
    const [, k, section, label, html] = m;
    if (seen.has(k)) continue;
    seen.add(k);
    const shared = k.startsWith("all.");
    items.push({ k, page: shared ? "all" : page, section, label, def: toText(html) });
  }
}
const pages = [["all", "All pages (top bar & footer)", "/"]].concat(PAGES.map((p) => [p[0], p[2], p[3]]));
const out = "// AUTO-GENERATED by scripts/build-texts.js — do not edit by hand.\n" +
  "export const TEXT_PAGES = " + JSON.stringify(pages) + ";\n" +
  "export const TEXTS = " + JSON.stringify(items, null, 0).replace(/\},\{/g, "},\n{") + ";\n";
fs.writeFileSync(path.join(ROOT, "worker", "texts-manifest.js"), out);
console.log("texts-manifest:", items.length, "editable texts");
